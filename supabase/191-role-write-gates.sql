-- 191-role-write-gates.sql  -  every table checks the role's level in its app.
--
-- The write rules on these tables let any active member whose role writes
-- somewhere save (can_write_company, from 190). This adds a second, restrictive
-- rule to each of them, which must also pass: inserting and changing a row needs
-- Own, Work or Manage in one of the apps that record it, and deleting needs the
-- same, or Manage for records that other records depend on (accounts, products,
-- contacts, projects, warehouses and each app's configuration).
--
-- A table written by several apps lists all of them: a stock movement is saved
-- by Inventory, Purchase, Sales, Manufacturing and the till, and a journal entry
-- by every app that posts. Posting itself stays in the functions that post.
--
-- Salaries: contracts, payslips and payroll runs are only readable by a role that
-- sees salaries, and a person can always read their own.
-- Nothing here touches reading any other table.
-- ============================================================================

