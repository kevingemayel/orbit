    ('tool_movements', '{manufacturing,site}'::text[], 'W', '(select t.company_id from public.tools t where t.id = tool_id)'),
    ('tools', '{manufacturing,site}'::text[], 'M', 'company_id'),
    ('trace_seals', '{accounting,purchase,inventory}'::text[], 'W', 'company_id'),
    ('training_bookings', '{employees}'::text[], 'W', 'company_id'),
    ('training_courses', '{employees}'::text[], 'M', 'company_id'),
    ('transmittal_items', '{documents,projects,site}'::text[], 'W', 'company_id'),
    ('transmittals', '{documents,projects,site}'::text[], 'W', 'company_id'),
    ('uoms', '{inventory,purchase,sales,kitchen,pos,manufacturing}'::text[], 'M', 'company_id'),
    ('user_company_access', '{settings}'::text[], 'M', 'company_id'),
    ('warehouses', '{inventory}'::text[], 'M', 'company_id'),
    ('waste_entries', '{kitchen,pos,inventory}'::text[], 'W', 'company_id'),
    ('waste_reasons', '{kitchen,pos,inventory}'::text[], 'M', 'company_id'),
    ('wholesale_accounts', '{kitchen,pos,sales}'::text[], 'W', 'company_id'),
    ('work_order_operations', '{manufacturing}'::text[], 'W', 'company_id'),
    ('work_orders', '{manufacturing,site,projects}'::text[], 'W', 'company_id')
  ) as v(tbl, mods, del, cexpr) loop
    execute format('drop policy if exists rg_ins on public.%I', g.tbl);
    execute format('drop policy if exists rg_upd on public.%I', g.tbl);
    execute format('drop policy if exists rg_del on public.%I', g.tbl);
    if g.tbl not in ('companies', 'backups') then
      execute format('create policy rg_ins on public.%I as restrictive for insert to authenticated with check (public.can_write_app(%s, %L::text[]))',
                     g.tbl, g.cexpr, g.mods);
    end if;
    if g.tbl <> 'backups' then
      execute format('create policy rg_upd on public.%I as restrictive for update to authenticated using (public.can_write_app(%s, %L::text[])) with check (public.can_write_app(%s, %L::text[]))',
                     g.tbl, g.cexpr, g.mods, g.cexpr, g.mods);
    end if;
    if g.tbl <> 'companies' then
      fn := case when g.del = 'M' then 'can_manage_app' else 'can_write_app' end;
      execute format('create policy rg_del on public.%I as restrictive for delete to authenticated using (public.%s(%s, %L::text[]))',
                     g.tbl, fn, g.cexpr, g.mods);
    end if;
  end loop;
end $gates$;

-- salaries are read by roles that see salaries, and by the person they belong to
drop policy if exists rg_salaries on public.hr_contracts;
create policy rg_salaries on public.hr_contracts as restrictive for select to authenticated
  using (public.can_see(company_id, 'salaries') or employee_id = public.my_employee_id(company_id));
drop policy if exists rg_salaries on public.hr_payslips;
create policy rg_salaries on public.hr_payslips as restrictive for select to authenticated
  using (public.can_see(company_id, 'salaries') or employee_id = public.my_employee_id(company_id));
drop policy if exists rg_salaries on public.hr_payslip_lines;
create policy rg_salaries on public.hr_payslip_lines as restrictive for select to authenticated
  using (public.can_see(company_id, 'salaries')
         or exists (select 1 from public.hr_payslips s where s.id = payslip_id and s.employee_id = public.my_employee_id(company_id)));
drop policy if exists rg_salaries on public.hr_payslip_runs;
create policy rg_salaries on public.hr_payslip_runs as restrictive for select to authenticated
  using (public.can_see(company_id, 'salaries'));
